/**
 * One row parsed out of a pasted message, before anyone has confirmed it.
 *
 * The parser guesses; the member corrects. Nothing is written until the
 * preview table is approved, which is why every field here is editable and
 * why `warnings` exists.
 */
export interface ParsedClientRow {
  id: string;
  name: string;
  whatHappened: string;
  city: string;
  contactName: string;
  contactPhone: string;
  stage: Stage;
  status: ClientStatus;
  closedReason: string;
  dealValueSar: number | null;
  /** Set when this looks like a company somebody already has. */
  duplicateOf: { clientId: string; ownerId: string; status: ClientStatus } | null;
  /** Unticked rows are skipped on save. */
  include: boolean;
  /** The original line, kept so the member can see what it came from. */
  raw: string;
}

export interface ParsedActivityRow {
  id: string;
  clientId: string;
  /** What the parser read as the client name, when it could not match one. */
  clientGuess: string;
  type: InteractionType;
  summary: string;
  /** yyyy-MM-dd */
  date: string;
  include: boolean;
  raw: string;
}

export interface SessionUser {
  id: string;
  slot: 1 | 2 | 3;
  name: string;
}
